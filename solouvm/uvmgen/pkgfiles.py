"""Maintain and validate ``<pkg>_files.svh`` package include lists (uvm-style.md §2.1, U-11)."""

from __future__ import annotations

import re
from collections.abc import Sequence
from pathlib import Path

from solouvm.errors import ConfigError

_INCLUDE_RE = re.compile(r'^\s*`include\s+"([^"]+)"')
_FILES_MARKER_RE = re.compile(r"^[ \t]*//[ \t]*solouvm:files\b", re.MULTILINE)
_FILES_BLOCK_RE = re.compile(
    r"^[ \t]*//[ \t]*solouvm:files[ \t]+begin[ \t]*\n"
    r".*?^[ \t]*//[ \t]*solouvm:files[ \t]+end[ \t]*(?:\n|$)",
    re.MULTILINE | re.DOTALL,
)

__all__ = [
    "expected_pkg_files",
    "find_svh_inconsistencies",
    "pkg_files_relpath",
    "render_pkg_files",
    "update_pkg_files",
]


def _strip_pkg_suffix(pkg: str) -> str:
    return pkg.removesuffix("_pkg")


def _component_order(pkg_base: str) -> dict[str, int]:
    if pkg_base.endswith("_env"):
        prefix = pkg_base.removesuffix("_env")
        ordered = (
            f"{prefix}_env_cfg.sv",
            f"{prefix}_scb.sv",
            f"{prefix}_ref.sv",
            f"{prefix}_vsqr.sv",
            f"{prefix}_cov.sv",
            f"{prefix}_env.sv",
        )
    elif pkg_base.endswith("_test"):
        prefix = pkg_base.removesuffix("_test")
        ordered = (f"{prefix}_base_test.sv",)
    else:
        prefix = pkg_base
        ordered = (
            f"{prefix}_txn.sv",
            f"{prefix}_cfg.sv",
            f"{prefix}_sqr.sv",
            f"{prefix}_drv.sv",
            f"{prefix}_mon.sv",
            f"{prefix}_cov.sv",
            f"{prefix}_agent.sv",
        )
    return {name: idx for idx, name in enumerate(ordered)}


def _sort_key(pkg_base: str, rel_to_verif: str) -> tuple[int, int, str]:
    order_map = _component_order(pkg_base)
    parts = Path(rel_to_verif).parts
    filename = parts[-1]
    in_seq_dir = len(parts) >= 4 and parts[-2] in ("seq", "vseq")
    if not in_seq_dir and filename in order_map:
        return (0, order_map[filename], rel_to_verif)
    if not in_seq_dir:
        return (1, 0, rel_to_verif)
    if pkg_base.endswith("_env"):
        prefix = pkg_base.removesuffix("_env")
        base_name = f"{prefix}_base_vseq.sv"
    else:
        base_name = f"{pkg_base}_base_seq.sv"
    if filename == base_name:
        return (2, 0, rel_to_verif)
    return (3, 0, rel_to_verif)


def sort_pkg_files(pkg_name: str, rel_files: Sequence[str]) -> list[str]:
    """Sort ``rel_files`` (relative to ``verif/``) in fixed uvm-style.md §2.1 order."""
    pkg_base = _strip_pkg_suffix(pkg_name)
    unique = set(rel_files)
    return sorted(unique, key=lambda item: _sort_key(pkg_base, item))


def render_pkg_files(pkg_name: str, rel_files: Sequence[str]) -> str:
    """Render deterministic ``<pkg>_files.svh`` content from ``rel_files``."""
    pkg_base = _strip_pkg_suffix(pkg_name)
    ordered = sort_pkg_files(pkg_base, rel_files)
    lines = [f"// {pkg_base}_files.svh -- generated by solouvm, do not edit"]
    lines.extend(f'`include "{rel}"' for rel in ordered)
    return "\n".join(lines) + "\n"


def merge_pkg_files(generated: str, previous: str) -> str:
    """Retain explicit include blocks and avoid regenerating their entries."""
    blocks = list(_FILES_BLOCK_RE.finditer(previous))
    if len(_FILES_MARKER_RE.findall(previous)) != 2 * len(blocks):
        raise ConfigError("unbalanced solouvm:files markers", code="CFG_INVALID")
    custom = {
        match.group(1)
        for block in blocks
        for line in block[0].splitlines()
        if (match := _INCLUDE_RE.match(line))
    }
    lines: list[str] = []
    positions: dict[str, int] = {}
    for line in generated.splitlines(keepends=True):
        match = _INCLUDE_RE.match(line)
        if match is not None:
            entry = match.group(1)
            if entry in custom:
                continue
            positions[entry] = len(lines)
        lines.append(line)
    insertions: dict[int, list[str]] = {}
    for block in blocks:
        position = next(
            (
                positions[entry.group(1)]
                for line in previous[block.end():].splitlines()
                if (entry := _INCLUDE_RE.match(line)) and entry.group(1) in positions
            ),
            len(lines),
        )
        insertions.setdefault(position, []).append(block[0].rstrip("\n") + "\n")
    output = []
    for index, line in enumerate(lines):
        output.extend(insertions.get(index, ()))
        output.append(line)
    output.extend(insertions.get(len(lines), ()))
    return "".join(output)


def _resolve_pkg_dir(root: Path, pkg: str, files: Sequence[str] | None = None) -> tuple[Path, str]:
    verif = Path(root) / "verif"
    raw = pkg.replace("\\", "/").strip("/")
    if raw.startswith("verif/"):
        raw = raw.removeprefix("verif/")
    if "/" in raw:
        parts = Path(raw).parts
        if len(parts) >= 2 and parts[0] == "agents":
            return verif / "agents" / parts[1], parts[1]
        if len(parts) >= 2 and parts[0] == "envs":
            return verif / "envs" / parts[1], f"{parts[1]}_env"
        if len(parts) >= 2 and parts[0] == "tests":
            return verif / "tests" / parts[1], f"{parts[1]}_test"

    stem = _strip_pkg_suffix(raw)
    if files:
        for item in files:
            norm = item.replace("\\", "/").removeprefix("verif/")
            if norm.startswith("agents/"):
                agent_name = Path(norm).parts[1]
                return verif / "agents" / agent_name, agent_name
            if norm.startswith("envs/"):
                env_name = Path(norm).parts[1]
                return verif / "envs" / env_name, f"{env_name}_env"
            if norm.startswith("tests/"):
                env_name = Path(norm).parts[1]
                return verif / "tests" / env_name, f"{env_name}_test"

    if (verif / "agents" / stem).is_dir():
        return verif / "agents" / stem, stem
    if stem.endswith("_env"):
        env_name = stem.removesuffix("_env")
        return verif / "envs" / env_name, stem
    if stem.endswith("_test"):
        env_name = stem.removesuffix("_test")
        return verif / "tests" / env_name, stem
    if (verif / "envs" / stem).is_dir():
        return verif / "envs" / stem, f"{stem}_env"
    if (verif / "tests" / stem).is_dir():
        return verif / "tests" / stem, f"{stem}_test"
    return verif / "agents" / stem, stem


def pkg_files_relpath(pkg_name: str) -> Path:
    """Return the relative path (from project root) of ``<pkg>_files.svh``."""
    stem = _strip_pkg_suffix(pkg_name)
    if stem.endswith("_env"):
        env_name = stem.removesuffix("_env")
        return Path("verif") / "envs" / env_name / f"{stem}_files.svh"
    if stem.endswith("_test"):
        env_name = stem.removesuffix("_test")
        return Path("verif") / "tests" / env_name / f"{stem}_files.svh"
    return Path("verif") / "agents" / stem / f"{stem}_files.svh"


def _normalize_rel_to_verif(root: Path, pkg_dir: Path, raw_path: str) -> str:
    verif = (Path(root) / "verif").resolve()
    candidate = Path(raw_path)
    if candidate.is_absolute():
        return candidate.resolve().relative_to(verif).as_posix()
    posix = raw_path.replace("\\", "/").lstrip("./")
    if posix.startswith("verif/"):
        return posix.removeprefix("verif/")
    if posix.startswith(("agents/", "envs/", "tests/")):
        return posix
    pkg_rel = pkg_dir.relative_to(Path(root) / "verif").as_posix()
    return f"{pkg_rel}/{posix}"


def expected_pkg_files(root: Path, pkg_dir: Path, pkg_name: str) -> list[str]:
    """Discover all ``.sv`` files belonging to ``pkg_dir`` in fixed include order."""
    root_path = Path(root)
    verif = root_path / "verif"
    pkg_base = _strip_pkg_suffix(pkg_name)
    if not pkg_dir.is_dir():
        return []
    discovered: list[str] = []
    for sv_file in pkg_dir.rglob("*.sv"):
        if not sv_file.is_file():
            continue
        name = sv_file.name
        if name.endswith("_pkg.sv") or name.endswith("_if.sv"):
            continue
        discovered.append(sv_file.relative_to(verif).as_posix())
    return sort_pkg_files(pkg_base, discovered)


def update_pkg_files(root: Path, pkg: str, files: list[str] | None = None) -> Path:
    """Write ``<pkg>_files.svh`` under ``root`` and return its path."""
    root_path = Path(root)
    pkg_dir, pkg_base = _resolve_pkg_dir(root_path, pkg, files)
    if files is None:
        rel_files = expected_pkg_files(root_path, pkg_dir, pkg_base)
    else:
        rel_files = [_normalize_rel_to_verif(root_path, pkg_dir, item) for item in files]
    pkg_dir.mkdir(parents=True, exist_ok=True)
    svh_path = pkg_dir / f"{pkg_base}_files.svh"
    generated = render_pkg_files(pkg_base, rel_files)
    if svh_path.is_file():
        generated = merge_pkg_files(generated, svh_path.read_text(encoding="utf-8"))
    svh_path.write_text(generated, encoding="utf-8")
    return svh_path


def find_svh_inconsistencies(root: Path) -> list[str]:
    """Check that every ``*_files.svh`` under ``verif/`` matches the ``.sv`` files on disk."""
    root_path = Path(root)
    verif = root_path / "verif"
    if not verif.is_dir():
        return []

    problems: list[str] = []
    groups: tuple[tuple[Path, str], ...] = (
        (verif / "agents", ""),
        (verif / "envs", "_env"),
        (verif / "tests", "_test"),
    )
    for parent, suffix in groups:
        if not parent.is_dir():
            continue
        for pkg_dir in sorted(p for p in parent.iterdir() if p.is_dir()):
            pkg_base = f"{pkg_dir.name}{suffix}"
            expected = expected_pkg_files(root_path, pkg_dir, pkg_base)
            pkg_sv_exists = (pkg_dir / f"{pkg_base}_pkg.sv").is_file()
            svh_path = pkg_dir / f"{pkg_base}_files.svh"
            svh_rel = svh_path.relative_to(root_path).as_posix()

            if not expected and not pkg_sv_exists and not svh_path.is_file():
                continue
            if not svh_path.is_file():
                problems.append(f"{svh_rel}: missing package file list for {pkg_base}")
                continue

            expected_set = set(expected)
            included: list[tuple[int, str]] = []
            seen_inc: set[str] = set()
            text = svh_path.read_text(encoding="utf-8")
            explicit_lines = {
                lineno
                for block in _FILES_BLOCK_RE.finditer(text)
                for lineno in range(
                    text.count("\n", 0, block.start()) + 1,
                    text.count("\n", 0, block.start()) + 1 + len(block[0].splitlines()),
                )
            }
            for lineno, line in enumerate(text.splitlines(), 1):
                match = _INCLUDE_RE.match(line)
                if match is None:
                    continue
                inc = match.group(1)
                included.append((lineno, inc))
                if inc in seen_inc:
                    problems.append(f"{svh_rel}:{lineno}: duplicate include {inc!r}")
                else:
                    seen_inc.add(inc)
                if not (verif / inc).is_file():
                    problems.append(f"{svh_rel}:{lineno}: included file does not exist: {inc!r}")
                elif inc not in expected_set and lineno not in explicit_lines:
                    problems.append(
                        f"{svh_rel}:{lineno}: included file {inc!r} does not belong to {pkg_base}"
                    )

            for exp in expected:
                if exp not in seen_inc:
                    problems.append(
                        f"{svh_rel}: {exp!r} is present on disk but not included in {svh_path.name}"
                    )

    return problems
