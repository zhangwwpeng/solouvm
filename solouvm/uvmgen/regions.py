"""Protected user region extraction, checksums, and merging (uvm-style.md §9, U-04, U-05)."""

from __future__ import annotations

import hashlib
import re

from solouvm.errors import ConfigError

_MARKER_PREFIX_RE = re.compile(r"^[ \t]*//\s*solouvm:user\b")
_BEGIN_RE = re.compile(
    r"^[ \t]*//\s*solouvm:user\s+begin\s+(?P<name>[A-Za-z0-9_.-]+)[ \t]*(?P<eol>\r?\n)?\Z"
)
_END_RE = re.compile(
    r"^[ \t]*//\s*solouvm:user\s+end\s+(?P<name>[A-Za-z0-9_.-]+)[ \t]*(?P<eol>\r?\n)?\Z"
)
_HEADER_RE = re.compile(
    r"^// generated by solouvm "
    r"\(style (?P<style>[^,)\s]+), "
    r"template (?P<template>[^@\s]+)@(?P<version>[^,\s)]+), "
    r"checksum (?P<checksum>[0-9a-fA-F]{8})\) "
    r"-- edit only inside user regions(?P<eol>\r?\n?)\Z"
)
_HEADER_ANY_CS_RE = re.compile(
    r"^(?P<prefix>// generated by solouvm "
    r"\(style [^,)\s]+, "
    r"template [^@\s]+@[^,\s)]+, "
    r"checksum )(?P<checksum>[^)\s]+)(?P<suffix>\) "
    r"-- edit only inside user regions\r?\n?)\Z"
)

__all__ = [
    "compute_checksum",
    "finalize_checksum",
    "format_header",
    "merge_regions",
    "parse_header",
    "user_regions",
]


def format_header(
    template: str,
    version: str | int = 1,
    checksum: str = "00000000",
    *,
    style: str | int = 1,
) -> str:
    """Format line 1 of a generated SystemVerilog file."""
    return (
        f"// generated by solouvm (style {style}, template {template}@{version}, "
        f"checksum {checksum}) -- edit only inside user regions"
    )


def parse_header(text: str) -> tuple[str, str, str, str] | None:
    """Extract ``(style, template, version, checksum)`` from line 1, or ``None``."""
    first_line = text.splitlines(keepends=False)[0] if text else ""
    match = _HEADER_RE.match(first_line)
    if match is None:
        return None
    return (
        match.group("style"),
        match.group("template"),
        match.group("version"),
        match.group("checksum"),
    )


def _scan_regions(text: str) -> tuple[dict[str, str], str]:
    """Validate and extract all ``solouvm:user`` regions and return ``(regions, stripped_text)``."""
    regions: dict[str, str] = {}
    stripped_lines: list[str] = []
    current_name: str | None = None
    body_lines: list[str] = []

    for lineno, line in enumerate(text.splitlines(keepends=True), 1):
        begin_match = _BEGIN_RE.match(line)
        end_match = _END_RE.match(line) if begin_match is None else None
        if begin_match is None and end_match is None and _MARKER_PREFIX_RE.match(line):
            raise ConfigError(
                f"malformed solouvm:user marker at line {lineno}: {line.strip()!r}",
                code="CFG_INVALID",
            )

        if current_name is None:
            if begin_match is not None:
                name = begin_match.group("name")
                if name in regions:
                    raise ConfigError(
                        f"duplicate solouvm:user region {name!r} at line {lineno}",
                        code="CFG_INVALID",
                    )
                current_name = name
                body_lines = []
                stripped_lines.append(line)
            elif end_match is not None:
                name = end_match.group("name")
                raise ConfigError(
                    f"unexpected solouvm:user end {name!r} at line {lineno} without begin",
                    code="CFG_INVALID",
                )
            else:
                stripped_lines.append(line)
        else:
            if begin_match is not None:
                name = begin_match.group("name")
                raise ConfigError(
                    f"nested solouvm:user region {name!r} inside {current_name!r} at line {lineno}",
                    code="CFG_INVALID",
                )
            if end_match is not None:
                end_name = end_match.group("name")
                if end_name != current_name:
                    raise ConfigError(
                        f"mismatched solouvm:user end {end_name!r} at line {lineno} "
                        f"(expected {current_name!r})",
                        code="CFG_INVALID",
                    )
                regions[current_name] = "".join(body_lines)
                current_name = None
                body_lines = []
                stripped_lines.append(line)
            else:
                body_lines.append(line)

    if current_name is not None:
        raise ConfigError(
            f"unclosed solouvm:user region {current_name!r}",
            code="CFG_INVALID",
        )
    return regions, "".join(stripped_lines)


def user_regions(text: str) -> dict[str, str]:
    """Extract ``{name: body}`` for every ``solouvm:user`` region in ``text``."""
    regions, _ = _scan_regions(text)
    return regions


def compute_checksum(text: str) -> str:
    """Compute the 8-hex sha1 checksum over ``text`` outside user-region bodies."""
    _, stripped = _scan_regions(text)
    lines = stripped.splitlines(keepends=True)
    if lines:
        header_match = _HEADER_ANY_CS_RE.match(lines[0])
        if header_match is not None:
            lines[0] = f"{header_match.group('prefix')}00000000{header_match.group('suffix')}"
    payload = "".join(lines).encode("utf-8")
    return hashlib.sha1(payload).hexdigest()[:8]


def finalize_checksum(text: str) -> str:
    """Recompute and write the line-1 checksum if ``text`` has a generated header."""
    checksum = compute_checksum(text)
    lines = text.splitlines(keepends=True)
    if not lines:
        return text
    header_match = _HEADER_ANY_CS_RE.match(lines[0])
    if header_match is None:
        return text
    lines[0] = f"{header_match.group('prefix')}{checksum}{header_match.group('suffix')}"
    return "".join(lines)


def merge_regions(new_text: str, old_text: str) -> tuple[str, dict[str, str], bool]:
    """Merge preserved user-region bodies from ``old_text`` into ``new_text``.

    Returns ``(merged_text, orphan_regions, modified_outside_regions)``.
    """
    old_regions = user_regions(old_text)
    new_regions = user_regions(new_text)

    old_header = parse_header(old_text)
    new_header = parse_header(new_text)
    if old_header is not None:
        modified_outside = compute_checksum(old_text).lower() != old_header[3].lower()
    elif new_header is not None:
        modified_outside = True
    else:
        modified_outside = compute_checksum(old_text) != compute_checksum(new_text)

    out_lines: list[str] = []
    current_name: str | None = None
    for line in new_text.splitlines(keepends=True):
        if current_name is None:
            begin_match = _BEGIN_RE.match(line)
            out_lines.append(line)
            if begin_match is not None:
                current_name = begin_match.group("name")
        else:
            end_match = _END_RE.match(line)
            if end_match is not None:
                preserved = old_regions.get(current_name, new_regions[current_name])
                if preserved and not preserved.endswith("\n"):
                    preserved += "\n"
                out_lines.append(preserved)
                out_lines.append(line)
                current_name = None

    merged = finalize_checksum("".join(out_lines))
    orphans = {
        name: body for name, body in old_regions.items() if name not in new_regions and body.strip()
    }
    return merged, orphans, modified_outside
