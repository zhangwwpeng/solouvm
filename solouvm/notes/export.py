def _cell(value: object) -> str:
    text = "-" if value is None else str(value)
    return text.replace("|", "\\|").replace("\r\n", " ").replace("\n", " ")


def _md_table(headers: list[str], rows: list[list[object]]) -> list[str]:
    out = [
        "| " + " | ".join(_cell(h) for h in headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in rows:
        out.append("| " + " | ".join(_cell(v) for v in row) + " |")
    return out


def _expect_summary(exp: Expect) -> str:
    parts: list[str] = []
    if exp.scoreboard is not None:
        desc = f"scoreboard `{exp.scoreboard}`"
        if exp.min is not None:
            desc += f" min={exp.min}"
        if exp.max is not None:
            desc += f" max={exp.max}"
        parts.append(desc)
    if exp.regex is not None:
        desc = f"regex `{exp.regex}`"
        if exp.count_min is not None:
            desc += f" count_min={exp.count_min}"
        if exp.count_max is not None:
            desc += f" count_max={exp.count_max}"
        if exp.min is not None:
            desc += f" min={exp.min}"
        if exp.max is not None:
            desc += f" max={exp.max}"
        parts.append(desc)
    if exp.sim_time_min is not None:
        parts.append(f"sim_time_min `{exp.sim_time_min}`")
    if exp.uvm_info_min is not None:
        parts.append(f"uvm_info_min={exp.uvm_info_min} id=`{exp.id}`")
    text = "; ".join(parts)
    if exp.reason:
        text += f" ({exp.reason})"
    return text


def _record_sort_key(index: int, record: object) -> tuple[int, str, str, int]:
    date_part = ""
    at_part = ""
    if isinstance(record, Bug):
        date_part = record.found or ""
        at_part = record.at or ""
    elif isinstance(record, Todo):
        date_part = record.due or (
            record.at[:10] if isinstance(record.at, str) and len(record.at) >= 10 else ""
        )
        at_part = record.at or ""
    elif isinstance(record, Log):
        date_part = record.date
        at_part = record.at or ""
    elif isinstance(record, Note):
        date_part = record.date or (
            record.at[:10] if isinstance(record.at, str) and len(record.at) >= 10 else ""
        )
        at_part = record.at or ""
    elif isinstance(record, Triage):
        date_part = record.at[:10] if isinstance(record.at, str) and len(record.at) >= 10 else ""
        at_part = record.at or ""
    return (0 if date_part else 1, date_part, at_part, index)


def _render_record_lines(case: Case, record: object, lbl: dict[str, str]) -> list[str]:
    if isinstance(record, Bug):
        dates = [f"found={record.found}"] if record.found else []
        if record.fixed:
            dates.append(f"fixed={record.fixed}")
        if record.verified:
            dates.append(f"verified={record.verified}")
        meta: list[str] = [f"status={record.status}", *dates]
        eff_owner = record.owner if record.owner is not None else case.owner
        if eff_owner:
            meta.append(f"{lbl['owner']}={eff_owner}")
        if record.seed is not None:
            meta.append(f"{lbl['seed']}={record.seed}")
        if record.signature:
            meta.append(f"{lbl['signature']}=`{record.signature}`")
        if record.link:
            meta.append(f"{lbl['link']}={record.link}")
        if record.author:
            meta.append(f"{lbl['author']}={record.author}")
        lines = [f"- **Bug `{case.name}#{record.id}`**: {record.title} ({', '.join(meta)})"]
        if record.body.strip():
            lines.append(f"  - {record.body.strip()}")
        return lines

    if isinstance(record, Todo):
        ident = f"{case.name}#{record.id}" if record.id is not None else case.name
        state = lbl["done"] if record.done else lbl["pending"]
        meta = [state]
        eff_owner = record.owner if record.owner is not None else case.owner
        if eff_owner:
            meta.append(f"{lbl['owner']}={eff_owner}")
        if record.due:
            meta.append(f"{lbl['due']}={record.due}")
        if record.author:
            meta.append(f"{lbl['author']}={record.author}")
        return [f"- **Todo `{ident}`**: {record.title} ({', '.join(meta)})"]

    if isinstance(record, Log):
        meta = [record.date]
        if record.author:
            meta.append(f"{lbl['author']}={record.author}")
        return [f"- **Log ({', '.join(meta)})**: {record.text}"]

    if isinstance(record, Note):
        meta = []
        if record.date:
            meta.append(record.date)
        if record.author:
            meta.append(f"{lbl['author']}={record.author}")
        suffix = f" ({', '.join(meta)})" if meta else ""
        return [f"- **Note{suffix}**: {record.text}"]

    if isinstance(record, Triage):
        rev = (
            str(record.review.get("decision", "pending"))
            if isinstance(record.review, dict)
            else "pending"
        )
        meta = [
            f"{lbl['verdict']}=`{record.verdict}`",
            f"{lbl['confidence']}=`{record.confidence}`",
            f"{lbl['review']}=`{rev}`",
        ]
        if record.author:
            meta.append(f"{lbl['author']}={record.author}")
        lines = [f"- **Triage `{record.task}`**: {record.summary} ({', '.join(meta)})"]
        if record.bugs:
            lines.append(f"  - Bugs: {', '.join(record.bugs)}")
        if record.doc:
            lines.append(f"  - {lbl['doc']}: `{record.doc}`")
        return lines

    return []


def _render_case_md(
    case: Case,
    *,
    lbl: dict[str, str],
    latest_run_id: str | None,
    case_jobs: list[dict[str, object]],
    with_results: bool,
) -> str:
    lines: list[str] = [
        GENERATED_MARKER,
        f"# {case.name}",
        "",
        f"## {lbl['overview']}",
        "",
        *_md_table(
            [
                lbl["stage"],
                lbl["owner"],
                lbl["uvm_test"],
                lbl["build"],
                lbl["tags"],
                lbl["seeds"],
                lbl["expect_fail"],
            ],
            [
                [
                    case.stage,
                    case.owner or "-",
                    case.uvm_test or "-",
                    case.build,
                    ", ".join(case.tags) if case.tags else "-",
                    case.seeds if case.seeds is not None else "-",
                    case.expect_fail,
                ]
            ],
        ),
    ]

    if case.doc:
        lines.extend(["", f"## {lbl['description']}", "", case.doc])

    if case.intent or case.method or case.spec_refs:
        lines.extend(["", f"## {lbl['verification']}", ""])
        if case.intent:
            lines.append(f"- **{lbl['intent']}**: {case.intent}")
        if case.method:
            lines.append(f"- **{lbl['method']}**: {case.method}")
        if case.spec_refs:
            lines.append(f"- **{lbl['spec_refs']}**: {', '.join(case.spec_refs)}")

    lines.extend(["", f"## {lbl['params']}", ""])
    if case.params:
        param_rows = [[k, case.params[k]] for k in sorted(case.params)]
        lines.extend(_md_table([lbl["param_key"], lbl["param_val"]], param_rows))
    else:
        lines.append(lbl["no_params"])

    lines.extend(["", f"## {lbl['expects']}", ""])
    if case.expect:
        for exp in case.expect:
            lines.append(f"- {_expect_summary(exp)}")
    else:
        lines.append(lbl["no_expects"])

    if with_results:
        lines.extend(["", f"## {lbl['latest_results_sec']}", ""])
        if latest_run_id is not None and case_jobs:
            lines.append(f"- {lbl['run_id']}: `{latest_run_id}`")
            lines.append("")
            job_rows = [
                [
                    j.get("job_id", ""),
                    j.get("seed", ""),
                    j.get("status", ""),
                    j.get("reason", ""),
                ]
                for j in sorted(case_jobs, key=lambda x: str(x.get("job_id", "")))
            ]
            lines.extend(
                _md_table([lbl["job"], lbl["seed"], lbl["status"], lbl["reason"]], job_rows)
            )
        else:
            lines.append(lbl["no_runs"])

    lines.extend(["", f"## {lbl['records']}", ""])
    ordered_records = [
        rec
        for _, rec in sorted(
            enumerate(case.notes),
            key=lambda pair: _record_sort_key(pair[0], pair[1]),
        )
    ]
    if ordered_records:
        for rec in ordered_records:
            lines.extend(_render_record_lines(case, rec, lbl))
    else:
        lines.append(lbl["no_records"])

    return "\n".join(lines) + "\n"


def _render_index_md(
    *,
    cases: list[Case],
    progress: dict[str, object],
    jobs_by_case: dict[str, list[dict[str, object]]],
    lbl: dict[str, str],
    with_results: bool,
) -> str:
    project = str(progress.get("project", ""))
    lines: list[str] = [
        GENERATED_MARKER,
        f"# {lbl['index_title'].format(project=project)}",
        "",
        f"## {lbl['progress']}",
        "",
        f"### {lbl['stages']}",
        "",
    ]

    stages = progress.get("stages")
    stages_dict = stages if isinstance(stages, dict) else {}
    stage_rows = [[name, count] for name, count in stages_dict.items()]
    stage_rows.append([lbl["total"], progress.get("total_cases", len(cases))])
    lines.extend(_md_table([lbl["stage"], lbl["count"]], stage_rows))

    if with_results:
        lines.extend(["", f"### {lbl['latest_run']}", ""])
        latest = progress.get("latest_run")
        if isinstance(latest, dict):
            rate = latest.get("pass_rate")
            rate_str = f"{rate:.1f}%" if isinstance(rate, (int, float)) else "-"
            lines.append(
                f"- {lbl['run_id']}: `{latest.get('run_id')}` | "
                f"{lbl['passed']}: {latest.get('passed', 0)}/{latest.get('total', 0)} | "
                f"{lbl['pass_rate']}: {rate_str}"
            )
        else:
            lines.append(lbl["no_runs"])

    by_owner = progress.get("by_owner")
    if isinstance(by_owner, dict) and by_owner:
        lines.extend(["", f"### {lbl['by_owner']}", ""])
        owner_rows = [
            [
                lbl["unassigned"] if owner == "<unassigned>" else owner,
                stats.get("open_bugs", 0),
                stats.get("fixed_bugs", 0),
                stats.get("open_todos", 0),
                stats.get("overdue_todos", 0),
            ]
            for owner, stats in by_owner.items()
            if isinstance(stats, dict)
        ]
        lines.extend(
            _md_table(
                [
                    lbl["owner"],
                    lbl["open_bugs"],
                    lbl["fixed_bugs"],
                    lbl["open_todos"],
                    lbl["overdue_todos"],
                ],
                owner_rows,
            )
        )

    overdue = progress.get("overdue_todos")
    if isinstance(overdue, list) and overdue:
        lines.extend(["", f"### {lbl['overdue_todos']}", ""])
        for item in overdue:
            if not isinstance(item, dict):
                continue
            lines.append(
                f"- `{item.get('id')}` [{item.get('owner')}] ({item.get('due')}): "
                f"{item.get('title')}"
            )

    hints = progress.get("hints")
    if with_results and isinstance(hints, list) and hints:
        lines.extend(["", f"### {lbl['hints']}", ""])
        for hint in hints:
            lines.append(f"- {hint}")

    lines.extend(["", f"## {lbl['unresolved_bugs']}", ""])
    bug_rows: list[list[object]] = []
    for case in cases:
        for rec in sorted(
            (r for r in case.notes if isinstance(r, Bug) and r.status in ("open", "fixed")),
            key=lambda b: b.id,
        ):
            eff_owner = rec.owner if rec.owner is not None else (case.owner or "-")
            bug_rows.append(
                [
                    f"{case.name}#{rec.id}",
                    f"[{case.name}]({case.name}.md)",
                    rec.status,
                    eff_owner,
                    rec.seed if rec.seed is not None else "-",
                    rec.found or "-",
                    rec.title,
                ]
            )
    if bug_rows:
        lines.extend(
            _md_table(
                [
                    "ID",
                    lbl["case"],
                    lbl["status"],
                    lbl["owner"],
                    lbl["seed"],
                    lbl["found"],
                    lbl["title"],
                ],
                bug_rows,
            )
        )
    else:
        lines.append(lbl["no_unresolved"])

    lines.extend(["", f"## {lbl['cases']}", ""])
    case_headers = [
        lbl["case"],
        lbl["stage"],
        lbl["owner"],
        lbl["tags"],
        lbl["open_bugs"],
        lbl["open_todos"],
    ]
    if with_results:
        case_headers.append(lbl["latest_result"])

    case_rows: list[list[object]] = []
    for case in cases:
        unresolved_cnt = sum(
            1 for r in case.notes if isinstance(r, Bug) and r.status in ("open", "fixed")
        )
        open_todo_cnt = sum(1 for r in case.notes if isinstance(r, Todo) and not r.done)
        row: list[object] = [
            f"[{case.name}]({case.name}.md)",
            case.stage,
            case.owner or "-",
            ", ".join(case.tags) if case.tags else "-",
            unresolved_cnt,
            open_todo_cnt,
        ]
        if with_results:
            cjobs = jobs_by_case.get(case.name, [])
            if cjobs:
                passed_cnt = sum(1 for j in cjobs if j.get("status") in PASS_STATUSES)
                row.append(f"{passed_cnt}/{len(cjobs)} pass")
            else:
                row.append("-")
        case_rows.append(row)

    lines.extend(_md_table(case_headers, case_rows))
    return "\n".join(lines) + "\n"


def export_docs(
    *,
    config: Config,
    out_dir: Path | None = None,
    lang: str | None = None,
    with_results: bool = True,
    today: date | None = None,
) -> dict[str, object]:
    """Export deterministic ``index.md`` and ``<case>.md`` docs and prune stale generated files."""
    eff_lang = lang if lang is not None else config.doc.lang
    if eff_lang not in _LABELS:
        raise ConfigError(
            f"unsupported doc language {eff_lang!r}; allowed: {', '.join(sorted(_LABELS))}",
            code="CFG_INVALID",
        )
    lbl = _LABELS[eff_lang]

    root = Path(config.root)
    raw_out = Path(out_dir) if out_dir is not None else Path(config.doc.out)
    target_dir = raw_out if raw_out.is_absolute() else root / raw_out
    target_dir.mkdir(parents=True, exist_ok=True)

    cases = sorted(collect_cases(config), key=lambda c: c.name)

    results_payload: dict[str, object] | None = _latest_results_data(root) if with_results else {}
    latest_run_id: str | None = None
    jobs_by_case: dict[str, list[dict[str, object]]] = {}
    if with_results and results_payload:
        raw_rid = results_payload.get("run_id")
        latest_run_id = str(raw_rid) if isinstance(raw_rid, str) else None
        for job in results_payload.get("jobs") or ():
            if isinstance(job, dict) and isinstance(job.get("case"), str):
                jobs_by_case.setdefault(job["case"], []).append(job)

    progress = compute_progress(
        config=config,
        cases=cases,
        results_data=results_payload,
        today=today,
    )

    generated: dict[str, str] = {
        "index.md": _render_index_md(
            cases=cases,
            progress=progress,
            jobs_by_case=jobs_by_case,
            lbl=lbl,
            with_results=with_results,
        )
    }
    for case in cases:
        generated[f"{case.name}.md"] = _render_case_md(
            case,
            lbl=lbl,
            latest_run_id=latest_run_id,
            case_jobs=jobs_by_case.get(case.name, []),
            with_results=with_results,
        )

    removed: list[str] = []
    for existing in sorted(target_dir.glob("*.md")):
        if existing.name in generated or not existing.is_file():
            continue
        try:
            content = existing.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        if content.startswith(_MARKER_PREFIX):
            existing.unlink()
            removed.append(str(existing))

    written_files: list[str] = []
    for filename, content in generated.items():
        dest = target_dir / filename
        dest.write_text(content, encoding="utf-8")
        written_files.append(str(dest))

    return {
        "out_dir": str(target_dir),
        "lang": eff_lang,
        "files": written_files,
        "removed": removed,
        "case_count": len(cases),
    }
