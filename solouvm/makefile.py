"""Rendering the generated artifacts: ``filelist.f`` and ``Makefile``.

Design note: ``solouvm`` generates one ``Makefile`` containing both the compile
target and per-case run targets. The README's "compile makefile + run makefile"
split is kept as a *logical* distinction (``solouvm gen`` builds both sections
from separate stages), not as two files: make already re-reads one file per run,
and two files made ``-j`` ordering fragile.
"""

from __future__ import annotations

import shlex
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from .config import Config
from .util import relpath, write_text_atomic

HEADER = "# generated by solouvm -- do not edit; run `solouvm gen` to refresh"


def filelist_text(cfg: Config, files: Sequence[str]) -> str:
    lines: list[str] = [f"// {HEADER}"]
    for incdir in cfg.incdirs:
        lines.append(f"+incdir+{incdir}")
    for define in cfg.defines:
        lines.append(f"+define+{define}")
    lines.extend(files)
    return "\n".join(lines) + "\n"


def render(cfg: Config, plan: Mapping[str, Any]) -> str:
    plan_rel = relpath(Path(cfg.workdir / "plan.json"), cfg.root)
    build_cmd = " ".join(shlex.quote(part) for part in _build_argv(cfg))
    case_ids = [item["case_id"] for item in plan["cases"]]
    run_targets = " ".join(f"run/{case_id}" for case_id in case_ids)

    lines = [
        HEADER,
        "",
        f"PYTHON ?= {shlex.quote(_python(cfg, plan))}",
        "SOLOUVM = $(PYTHON) -m solouvm",
        f"PLAN = {plan_rel}",
        f"JOBS ?= {cfg.jobs}",
        "",
        ".PHONY: all build run regress _finalize clean",
        "all: build",
        "",
        "build:",
        f"\t@cd {shlex.quote(str(cfg.root))} && {build_cmd}",
        "",
        "run: regress",
        "",
    ]

    for case_id in case_ids:
        lines.extend(
            [
                f"run/{case_id}: build",
                f"\t@$(SOLOUVM) _exec --plan $(PLAN) --case-id {case_id} $(SOLOUVM_EXEC_FLAGS)",
                "",
            ]
        )

    lines.extend(
        [
            f"regress: {run_targets}",
            "",
            "_finalize:",
            "\t@$(SOLOUVM) end --plan $(PLAN)",
            "",
            "clean:",
            f"\t@rm -rf {shlex.quote(str(Path(cfg.workdir) / 'out'))}",
            "",
        ]
    )
    return "\n".join(lines)


def write_filelist(cfg: Config, files: Sequence[str]) -> Path:
    filelist = cfg.root / "filelist.f"
    write_text_atomic(filelist, filelist_text(cfg, files))
    return filelist


def write_make(cfg: Config, plan: Mapping[str, Any]) -> list[Path]:
    """Write ``.solouvm/Makefile`` plus a root delegating Makefile (if free)."""
    written: list[Path] = []
    makefile = cfg.workdir / "Makefile"
    write_text_atomic(makefile, render(cfg, plan))
    written.append(makefile)

    root_makefile = cfg.root / "Makefile"
    if not root_makefile.exists():
        write_text_atomic(
            root_makefile,
            f"{HEADER}\n\ninclude {relpath(makefile, cfg.root)}\n",
        )
        written.append(root_makefile)
    return written


def write(cfg: Config, plan: Mapping[str, Any], files: Sequence[str]) -> list[Path]:
    """Write every generated artifact (sources + make targets)."""
    written = [write_filelist(cfg, files)]
    written.extend(write_make(cfg, plan))
    return written


def _build_argv(cfg: Config) -> list[str]:
    from . import simulator

    return simulator.build_argv(cfg)


def _python(cfg: Config, plan: Mapping[str, Any]) -> str:
    return str(plan.get("python") or "python3")
