HIER_REF_HINT = (
    "move code that references the DUT hierarchy into the 'top' file group (see doc/config.md §4.1)"
)

_PACKAGE_RE = re.compile(r"^\s*package\s+(?:automatic\s+|static\s+)?(\w+)\s*;", re.MULTILINE)
_COMMENT_RE = re.compile(r"//[^\n]*|/\*.*?\*/", re.DOTALL)
_SHELL_OPS = frozenset({"&&", "||", ";", "|"})

_VERILATOR_DIAG_RE = re.compile(
    r"^%(?P<severity>Error|Warning)(?:-[A-Z0-9_]+)?:\s*"
    r"(?P<file>[^:\s]+):(?P<line>\d+):(?:(?P<col>\d+):)?\s*(?P<message>.+?)\s*$"
)
_QUESTA_DIAG_RE = re.compile(
    r"^\*\*\s*(?P<severity>Error|Fatal|Warning)(?:\s*\([^)]*\))?:\s*"
    r"(?P<file>.+?)\((?P<line>\d+)\):\s*(?P<message>.+?)\s*$"
)
_XCELIUM_DIAG_RE = re.compile(
    r"^(?:xm|nc)(?:vlog|elab|sim):\s*\*(?P<sev>[EWF]),\S+\s*"
    r"\((?P<file>[^,]+),(?P<line>\d+)(?:\|(?P<col>\d+))?\):\s*(?P<message>.+?)\s*$"
)
_VCS_ERR_RE = re.compile(r"^Error-\[(?P<code>[^\]]+)\]\s*(?P<message>.*)$")
_VCS_LOC_RE = re.compile(r'(?:"(?P<qfile>[^"]+)"|(?P<file>[^\s:,]+))\s*[,:]\s*(?P<line>\d+)')

_HIER_REF_RE = re.compile(
    r"hierarchical\s+(?:reference|name|path|identifier)"
    r"|cross-module\s+reference"
    r"|Error-\[XMRE\]"
    r"|\*E,CUVHNF"
    r"|unable\s+to\s+bind"
    r"|can't\s+locate\s+varref\s+scope"
    r"|unresolved\s+(?:hierarchical|cross-module)?\s*reference"
    r"|failed\s+to\s+find\s+.*\s+in\s+hierarchical"
    r"|cannot\s+resolve\s+hierarchical"
    r"|cannot\s+be\s+resolved\s+in\s+fake_top",
    re.IGNORECASE,
)


@dataclass
class FakeTopResult:
    """Outcome of Layer 2 ``fake_top`` compilation."""

    ok: bool
    skipped: bool = False
    packages: list[str] = field(default_factory=list)
    duration_s: float = 0.0
    diagnostics: list[CheckDiagnostic] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


def _strip_sv_comments(text: str) -> str:
    def repl(match: re.Match[str]) -> str:
        raw = match.group(0)
        return re.sub(r"[^\n]", " ", raw)

    return _COMMENT_RE.sub(repl, text)


def extract_tb_packages(root: Path, tb_files: list[str]) -> list[str]:
    """Extract SystemVerilog package names from ``tb_files`` in list order."""
    root_path = Path(root)
    packages: list[str] = []
    seen: set[str] = {"uvm_pkg"}
    for raw in tb_files:
        if "$" in raw:
            continue
        candidate = Path(raw) if os.path.isabs(raw) else root_path / raw
        if not candidate.is_file():
            continue
        try:
            content = candidate.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        cleaned = _strip_sv_comments(content)
        for match in _PACKAGE_RE.finditer(cleaned):
            pkg_name = match.group(1)
            if pkg_name not in seen:
                seen.add(pkg_name)
                packages.append(pkg_name)
    return packages


def generate_fake_top(root: Path, packages: Sequence[str]) -> Path:
    """Write ``.solouvm/check/fake_top.sv`` importing ``uvm_pkg::*`` and ``packages``."""
    check_dir = Path(root) / CHECK_REL_DIR
    check_dir.mkdir(parents=True, exist_ok=True)
    lines = [
        "// generated by solouvm -- do not edit",
        "module solouvm_fake_top;",
        "  import uvm_pkg::*;",
    ]
    for pkg in packages:
        lines.append(f"  import {pkg}::*;")
    lines.append("endmodule")
    out_path = check_dir / "fake_top.sv"
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out_path


def write_tb_filelist(config: Config, files: FileList) -> Path:
    """Write ``.solouvm/check/filelist.tb.f`` with paths relative to ``.solouvm/check``."""
    root = Path(os.path.normpath(Path(config.root).absolute()))
    resolved_root = root.resolve()
    check_dir = root / CHECK_REL_DIR
    check_dir.mkdir(parents=True, exist_ok=True)

    outside_map = {entry.path: entry.outside_root for entry in files.entries}
    raw_lines: list[str] = []
    for define in [*config.defines, *files.defines.get("tb", [])]:
        check_no_newlines(define, field="defines")
        raw_lines.append(f"+define+{define}")
    for incdir in [*config.incdirs, *files.incdirs.get("tb", [])]:
        formatted = format_check_path(root, resolved_root, incdir, expand_local=False)
        raw_lines.append(f"+incdir+{formatted}")
    for lib in files.libs.get("tb", []):
        check_no_newlines(lib, field="files.libs['tb']")
        if lib.startswith(("-v ", "-y ")):
            formatted = format_check_path(root, resolved_root, lib[3:], expand_local=False)
            raw_lines.append(f"{lib[:3]}{formatted}")
        else:
            raw_lines.append(lib)
    for file_path in files.groups.get("tb", []):
        raw_lines.append(
            format_check_path(
                root,
                resolved_root,
                file_path,
                expand_local=False,
                outside=outside_map.get(file_path),
            )
        )

    seen_directives: set[str] = set()
    lines: list[str] = []
    for line in raw_lines:
        if line.startswith(("+define+", "+incdir+")):
            if line in seen_directives:
                continue
            seen_directives.add(line)
        lines.append(line)

    dotf_path = check_dir / "filelist.tb.f"
    dotf_path.write_text("\n".join(lines) + "\n" if lines else "", encoding="utf-8")
    return dotf_path


def ensure_check_scripts(root: Path, backend: Backend) -> list[str]:
    """Ensure ``.solouvm/gen/bin/run_job.sh`` (and ``fake_sim.sh`` if needed) exist."""
    written: list[str] = []
    run_job_rel = ".solouvm/gen/bin/run_job.sh"
    run_job_path = root / run_job_rel
    if not run_job_path.exists():
        run_job_path.parent.mkdir(parents=True, exist_ok=True)
        run_job_path.write_text(render_run_job(), encoding="utf-8")
        run_job_path.chmod(0o755)
    written.append(run_job_rel)

    if backend.name == "fake" or "fake_sim.sh" in backend.compile_only:
        fake_rel = ".solouvm/gen/bin/fake_sim.sh"
        fake_path = root / fake_rel
        if not fake_path.exists():
            fake_path.parent.mkdir(parents=True, exist_ok=True)
            fake_path.write_text(fake_sim_source(), encoding="utf-8")
            fake_path.chmod(0o755)
        written.append(fake_rel)
    return written


def expand_compile_only_cmd(backend: Backend, config: Config) -> tuple[list[str], str]:
    """Expand ``backend.compile_only`` placeholders relative to ``.solouvm/check``."""
    template = backend.compile_only.strip()
    if not template:
        raise ConfigError(
            f"backend {backend.name!r} has empty compile_only template",
            code="CFG_INVALID",
        )
    ctx = {
        "root": relpath(".", CHECK_REL_DIR),
        "check_dir": relpath(CHECK_REL_DIR, CHECK_REL_DIR),
        "fake_top": relpath(f"{CHECK_REL_DIR}/fake_top.sv", CHECK_REL_DIR),
        "filelist_tb": relpath(f"{CHECK_REL_DIR}/filelist.tb.f", CHECK_REL_DIR),
        "filelist": relpath(f"{CHECK_REL_DIR}/check.f", CHECK_REL_DIR),
        "filelist_rtl": relpath(".solouvm/gen/filelist.rtl.f", CHECK_REL_DIR),
        "filelist_top": relpath(".solouvm/gen/filelist.top.f", CHECK_REL_DIR),
        "top": config.top,
        "build_dir": ".",
        "simv": backend.simv,
    }
    try:
        raw_tokens = shlex.split(template)
    except ValueError as exc:
        raise ConfigError(
            f"backend {backend.name!r} compile_only: invalid command syntax: {exc}",
            code="CFG_INVALID",
        ) from None
    expanded = [
        check_no_newlines(
            expand_template(tok, ctx, where=f"backend {backend.name!r} compile_only"),
            field="compile_only",
        )
        for tok in raw_tokens
    ]
    if not expanded:
        raise ConfigError(
            f"backend {backend.name!r} compile_only expanded to empty command",
            code="CFG_INVALID",
        )
    primary_bin = expanded[0]
    if any(tok in _SHELL_OPS for tok in expanded):
        shell_parts = [
            tok if tok in _SHELL_OPS else sh_quote(tok, field="compile_only") for tok in expanded
        ]
        return ["bash", "-c", " ".join(shell_parts)], primary_bin
    return expanded, primary_bin


def _read_text_from_transport(provider: Provider, rel_path: str) -> str:
    if not provider.transport.exists(rel_path):
        return ""
    return "\n".join(line for _, line in provider.transport.read_lines(rel_path))


def run_check_job(
    *,
    root: Path,
    provider: Provider,
    where: str,
    cmd_tokens: Sequence[str],
    log_name: str,
    push_files: Sequence[str],
) -> tuple[int, str, float]:
    """Execute ``cmd_tokens`` via ``.solouvm/gen/bin/run_job.sh`` under ``.solouvm/check``."""
    check_dir = root / CHECK_REL_DIR
    check_dir.mkdir(parents=True, exist_ok=True)
    log_rel = f"{CHECK_REL_DIR}/{log_name}"
    facts_rel = f"{CHECK_REL_DIR}/job.facts"

    run_job_argv = [
        "bash",
        ".solouvm/gen/bin/run_job.sh",
        "--kind",
        "check",
        "--dir",
        CHECK_REL_DIR,
        "--log",
        log_name,
    ]
    if provider.setup:
        run_job_argv.extend(["--setup", provider.setup])
    run_job_argv.append("--")
    run_job_argv.extend(cmd_tokens)

    start = time.monotonic()
    if where == "local":
        log_command(run_job_argv)
        try:
            proc = subprocess.run(
                run_job_argv,
                cwd=str(root),
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                check=False,
            )
        except OSError as exc:
            raise InfraError(
                f"failed to run check wrapper: {exc}",
                code="CHECK_UNAVAILABLE",
            ) from exc
        rc = proc.returncode
        log_file = root / log_rel
        log_text = (
            log_file.read_text(encoding="utf-8", errors="replace") if log_file.is_file() else ""
        )
        if not log_text and (proc.stderr or proc.stdout):
            log_text = "\n".join(p for p in (proc.stdout, proc.stderr) if p.strip())
        facts_file = root / facts_rel
        facts_text = (
            facts_file.read_text(encoding="utf-8", errors="replace") if facts_file.is_file() else ""
        )
    else:
        provider.sync.push(provider.transport, str(root), list(push_files))
        exec_capture = getattr(provider.transport, "exec_capture", None)
        exec_output = getattr(provider.transport, "exec_output", None)
        extra_out = ""
        if callable(exec_capture):
            rc, out, err = exec_capture(run_job_argv, cwd=".", check=False)
            extra_out = "\n".join(p for p in (out, err) if p.strip())
        elif callable(exec_output):
            rc, extra_out = exec_output(run_job_argv, cwd=".", check=False)
        else:
            rc = provider.transport.exec(run_job_argv, cwd=".", check=False)
        log_text = _read_text_from_transport(provider, log_rel)
        if not log_text and extra_out:
            log_text = extra_out
        facts_text = _read_text_from_transport(provider, facts_rel)

    duration_s = time.monotonic() - start
    if facts_text.strip():
        with contextlib.suppress(FactsError):
            facts = parse_facts(facts_text)
            if facts.duration_s is not None:
                duration_s = facts.duration_s
    return rc, log_text, duration_s


def _with_hier_hint(
    *,
    file: str,
    line: int,
    col: int,
    severity: str,
    message: str,
    context_text: str,
) -> CheckDiagnostic:
    hint = HIER_REF_HINT if severity == "error" and _HIER_REF_RE.search(context_text) else None
    return CheckDiagnostic(
        file=file,
        line=line,
        col=col,
        severity=severity,
        message=message,
        hint=hint,
    )


def parse_simulator_diagnostics(
    log_text: str,
    *,
    root: Path,
    backend: Backend,
) -> list[CheckDiagnostic]:
    """Parse simulator compile diagnostics and attach E-05 hierarchical-reference hints."""
    lines = log_text.splitlines()
    diags: list[CheckDiagnostic] = []
    matched_indices: set[int] = set()

    for idx, raw_line in enumerate(lines):
        stripped = raw_line.strip()
        if not stripped:
            continue

        # 1. Verilator: %Error[-CODE]: file:line[:col]: msg
        ver_m = _VERILATOR_DIAG_RE.match(stripped)
        if ver_m is not None:
            matched_indices.add(idx)
            sev = "warning" if ver_m.group("severity").lower() == "warning" else "error"
            msg = ver_m.group("message").strip()
            diags.append(
                _with_hier_hint(
                    file=normalize_diag_path(ver_m.group("file"), root),
                    line=int(ver_m.group("line")),
                    col=int(ver_m.group("col") or 0),
                    severity=sev,
                    message=msg,
                    context_text=stripped,
                )
            )
            continue

        # 2. Questa: ** Error: file(line): msg
        qst_m = _QUESTA_DIAG_RE.match(stripped)
        if qst_m is not None:
            matched_indices.add(idx)
            sev = "warning" if qst_m.group("severity").lower() == "warning" else "error"
            msg = qst_m.group("message").strip()
            diags.append(
                _with_hier_hint(
                    file=normalize_diag_path(qst_m.group("file"), root),
                    line=int(qst_m.group("line")),
                    col=0,
                    severity=sev,
                    message=msg,
                    context_text=stripped,
                )
            )
            continue

        # 3. Xcelium: xmvlog: *E,CODE (file,line|col): msg
        xcel_m = _XCELIUM_DIAG_RE.match(stripped)
        if xcel_m is not None:
            matched_indices.add(idx)
            sev = "warning" if xcel_m.group("sev") == "W" else "error"
            msg = xcel_m.group("message").strip()
            diags.append(
                _with_hier_hint(
                    file=normalize_diag_path(xcel_m.group("file"), root),
                    line=int(xcel_m.group("line")),
                    col=int(xcel_m.group("col") or 0),
                    severity=sev,
                    message=msg,
                    context_text=stripped,
                )
            )
            continue

        # 4. VCS: Error-[CODE] msg (with possible file/line in following lines)
        vcs_m = _VCS_ERR_RE.match(stripped)
        if vcs_m is not None:
            matched_indices.add(idx)
            block_lines = [stripped]
            err_file = ""
            err_line = 0
            for look_idx in range(idx + 1, min(len(lines), idx + 6)):
                nxt = lines[look_idx].strip()
                if not nxt or _VCS_ERR_RE.match(nxt):
                    break
                block_lines.append(nxt)
                if not err_file:
                    loc_m = _VCS_LOC_RE.search(nxt)
                    if loc_m is not None:
                        raw_f = loc_m.group("qfile") or loc_m.group("file") or ""
                        err_file = normalize_diag_path(raw_f, root)
                        err_line = int(loc_m.group("line"))
            code = vcs_m.group("code")
            head_msg = vcs_m.group("message").strip()
            msg = f"[{code}] {head_msg}".strip()
            diags.append(
                _with_hier_hint(
                    file=err_file,
                    line=err_line,
                    col=0,
                    severity="error",
                    message=msg,
                    context_text="\n".join(block_lines),
                )
            )
            continue

        # 5. Generic file:line[:col]: error|warning: msg
        txt_diags = parse_text_diagnostics(stripped, root)
        if txt_diags:
            matched_indices.add(idx)
            for td in txt_diags:
                diags.append(
                    _with_hier_hint(
                        file=td.file,
                        line=td.line,
                        col=td.col,
                        severity=td.severity,
                        message=td.message,
                        context_text=stripped,
                    )
                )

    # 6. Fallback to backend.error_regex on unmatched lines if no structured error found
    if not any(d.severity == "error" for d in diags) and backend.error_regex:
        compiled = [re.compile(pat) for pat in backend.error_regex]
        for idx, raw_line in enumerate(lines):
            if idx in matched_indices:
                continue
            stripped = raw_line.strip()
            if stripped and any(rx.search(stripped) for rx in compiled):
                diags.append(
                    _with_hier_hint(
                        file="",
                        line=0,
                        col=0,
                        severity="error",
                        message=stripped,
                        context_text=log_text,
                    )
                )

    # Attach E-05 hint if hierarchical-reference indicator appears in log context
    if diags and _HIER_REF_RE.search(log_text):
        updated: list[CheckDiagnostic] = []
        any_hinted = any(d.hint == HIER_REF_HINT for d in diags)
        for diag in diags:
            if not any_hinted and diag.severity == "error" and diag.hint is None:
                updated.append(
                    CheckDiagnostic(
                        file=diag.file,
                        line=diag.line,
                        col=diag.col,
                        severity=diag.severity,
                        message=diag.message,
                        hint=HIER_REF_HINT,
                    )
                )
                any_hinted = True
            else:
                updated.append(diag)
        return updated

    return diags


def _matches_license_failure(log_text: str, backend: Backend) -> bool:
    return any(re.search(pat, log_text) for pat in backend.license_regex)


def run_faketop(
    *,
    config: Config,
    files: FileList,
    backend: Backend,
    provider: Provider,
    where: str,
) -> FakeTopResult:
    """Run Layer 2 ``fake_top`` tb-only compilation check (E-04, E-05)."""
    tb_files = files.groups.get("tb", [])
    if not tb_files:
        return FakeTopResult(
            ok=True,
            skipped=True,
            warnings=["tb file group is empty; skipping fake_top check"],
        )

    root = Path(os.path.normpath(Path(config.root).absolute()))
    packages = extract_tb_packages(root, tb_files)
    generate_fake_top(root, packages)
    write_tb_filelist(config, files)
    script_files = ensure_check_scripts(root, backend)
    cmd_tokens, primary_bin = expand_compile_only_cmd(backend, config)

    push_files = [
        *script_files,
        f"{CHECK_REL_DIR}/fake_top.sv",
        f"{CHECK_REL_DIR}/filelist.tb.f",
    ]
    rc, log_text, duration_s = run_check_job(
        root=root,
        provider=provider,
        where=where,
        cmd_tokens=cmd_tokens,
        log_name="check_faketop.log",
        push_files=push_files,
    )

    diagnostics = parse_simulator_diagnostics(log_text, root=root, backend=backend)
    error_count = sum(1 for d in diagnostics if d.severity == "error")

    if rc != 0 and error_count == 0:
        if is_missing_binary_output(rc, log_text, primary_bin):
            raise InfraError(
                f"simulator {backend.name!r} command {primary_bin!r} is unavailable",
                code="CHECK_UNAVAILABLE",
                hint="ensure simulator is on PATH or configure provider.setup",
            )
        if _matches_license_failure(log_text, backend):
            raise InfraError(
                f"simulator license failure while running {backend.name!r} fake_top check",
                code="CHECK_UNAVAILABLE",
                hint="check EDA license availability or retry later",
            )
        non_empty = [ln.strip() for ln in log_text.splitlines() if ln.strip()]
        msg = non_empty[-1] if non_empty else f"{backend.name} compile_only failed with exit {rc}"
        hint = HIER_REF_HINT if _HIER_REF_RE.search(log_text) else None
        diagnostics.append(
            CheckDiagnostic(file="", line=0, col=0, severity="error", message=msg, hint=hint)
        )
        error_count = 1

    ok = rc == 0 and error_count == 0
    return FakeTopResult(
        ok=ok,
        skipped=False,
        packages=packages,
        duration_s=duration_s,
        diagnostics=diagnostics,
    )
