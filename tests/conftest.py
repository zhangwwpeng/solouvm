"""Shared fixtures: build a throwaway project and drive the CLI in-process."""

from __future__ import annotations

import json
import pprint
import sys
from dataclasses import dataclass
from pathlib import Path

import pytest

from solouvm.cli import main

FAKE_SIM = Path(__file__).with_name("fake_sim.py")


@dataclass
class Project:
    root: Path

    @property
    def workdir(self) -> Path:
        return self.root / ".solouvm"

    def run(self, *args: str) -> int:
        argv = ["-c", str(self.root / "solouvm.conf.py"), *args]
        return main(argv)

    def plan(self) -> dict:
        return json.loads((self.workdir / "plan.json").read_text())

    def status(self, case_id: str) -> dict:
        path = self.workdir / "out" / case_id / "status.json"
        return json.loads(path.read_text())

    def results(self) -> dict:
        return json.loads((self.workdir / "results.json").read_text())

    def log(self, case_id: str) -> str:
        return (self.workdir / "out" / case_id / "sim.log").read_text()


@pytest.fixture
def make_project(tmp_path: Path):
    def _make(
        cases: list[dict] | None = None,
        *,
        seeds: object = [1],
        timeout: object = "10s",
        retry: int = 0,
        checks: dict | None = None,
        files: tuple[str, ...] = ("rtl/dut.sv",),
        case_source: str | None = None,
        filelist_source: str | None = None,
        config_extra: dict | None = None,
    ) -> Project:
        root = tmp_path / "proj"
        root.mkdir(exist_ok=True)
        for name in files:
            target = root / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text("// stub\n")

        cfg = {
            "project": "demo",
            "simulator": "fake",
            "top": "tb_top",
            "workdir": ".solouvm",
            "files": None,
            "regress": {"seeds": seeds, "retry": retry, "jobs": 1},
            "run": {"timeout": timeout, "opts": []},
            "checks": {
                "pass_regex": [],
                "fail_regex": [],
                "max_uvm_error": 0,
                "max_uvm_fatal": 0,
            },
            "sim": {
                "build": "echo build-ok",
                "run": [sys.executable, str(FAKE_SIM)],
            },
        }
        if checks:
            cfg["checks"].update(checks)
        if config_extra:
            cfg.update(config_extra)
        cfg.pop("files")

        (root / "solouvm.conf.py").write_text(
            "# generated by tests\nCFG = " + pprint.pformat(cfg, width=88, sort_dicts=False) + "\n"
        )

        if filelist_source is None:
            entries = ", ".join(repr(name) for name in files)
            filelist_source = f"FILES = [{entries}]\n"
        (root / "filelist.py").write_text(filelist_source)

        if case_source is None:
            rows = cases if cases is not None else [
                {"name": "smoke", "uvm_test": "smoke_test", "params": {"MODE": "pass"}}
            ]
            lines = ["from solouvm import Case", "", "CASES = ["]
            for row in rows:
                items = ", ".join(f"{key}={value!r}" for key, value in row.items())
                lines.append(f"    Case({items}),")
            lines.extend(["]", ""])
            case_source = "\n".join(lines)
        (root / "case.py").write_text(case_source)
